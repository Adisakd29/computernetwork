# Part 14 (3.0 Phase 5): Student Network Skills Portfolio, capstone defense rubric, practice gate
# - student: portfolio page (10 skills, rubric, evidence, capstone, 18 weeks), reflection saved, phone layout, print view
# - teacher: class overview, open a student's portfolio, record class evidence, comment, score the capstone defense
# - class option "practical before the post-test" (3.2: the week practical) locks the post-test in the student's page and unlocks after passing
# usage: python3 tests/e2e/part14.py <out-dir>
import asyncio, sys, os, subprocess
from playwright.async_api import async_playwright
OUT=sys.argv[1]; BASE=os.environ.get('E2E_BASE','http://127.0.0.1:3990')
DB=os.environ.get('E2E_DATABASE_URL','postgres://postgres@127.0.0.1:5433/netlab_e2e')
issues=[]
def bad(m): issues.append(m); print('  ✗',m)
def ok(m): print('  ✓',m)
def check(c,m): ok(m) if c else bad(m)
def sql(q): return subprocess.check_output(['psql',DB,'-tAqc',q]).decode().strip()
async def login(ctx,u,p):
    r=await ctx.request.post(BASE+'/api/auth/login',data={'username':u,'password':p},headers={'X-NetLab':'1'}); assert r.ok, await r.text()

async def main():
    sid=sql("SELECT id FROM users WHERE username='s1'")
    # evidence a student would have after some weeks: two missions graded on the server and a capstone submission
    sql(f"INSERT INTO sim_results(user_id,sim,mission,best,max,last,attempts,first_full_at) VALUES({sid},'wifi','wf2',10,10,10,1,now()),({sid},'switching','sw3',10,10,10,2,now()),({sid},'topology','t9',26,30,26,1,NULL) ON CONFLICT DO NOTHING")
    sql(f"INSERT INTO sim_submissions(user_id,sim,mission,payload,auto_score,auto_max,rubric,report) VALUES({sid},'topology','t9','{{}}',26,30,'[{{\"id\":\"vlsm\",\"title\":\"แผน IP แบบ VLSM\",\"score\":8,\"max\":8}}]','แบ่ง 172.16.10.0/24 เป็น /26 /27 /28 ตามจำนวนเครื่อง ทดสอบ ping ข้ามวงผ่านทุกวง')")
    async with async_playwright() as p:
        b=await p.chromium.launch()
        print('== student portfolio')
        S=await b.new_context(viewport={'width':1366,'height':900}); await login(S,'s1','Stud1234'); pg=await S.new_page(); E=[]; pg.on('pageerror',lambda e:E.append(str(e)))
        await pg.goto(BASE+'/#/'); await pg.wait_for_selector('.side')
        try: await pg.wait_for_selector('.side a[href="#/portfolio"]',timeout=8000); ok('sidebar has "แฟ้มผลงานทักษะ"')
        except Exception: bad('sidebar has "แฟ้มผลงานทักษะ"')
        await pg.goto(BASE+'/#/portfolio'); await pg.wait_for_selector('.pf .pfsk')
        check(await pg.locator('.pf .pfsk').count()==10,'10 skill cards in the summary')
        t=await pg.inner_text('.pf')
        check('สมชาย ทดสอบ' in t and 'ปวช.2/4' in t,'header shows the student and class')
        wl=pg.locator('#pf-wireless'); wt=await wl.inner_text()
        check('วาง AP 2 ตัว' in wt and 'กำลังพัฒนา' in wt,'wireless shows the passed Wi-Fi mission as dated evidence and its level')
        check(await wl.locator('table.rub td.on').count()==2,'the rubric row of the current level is highlighted')
        cp=await pg.inner_text('#pf-capstone')
        check('26/30' in cp and 'แบ่ง 172.16.10.0/24' in cp and 'ยังไม่ได้ประเมิน' in cp,'capstone shows the auto score, the report and the not-yet-scored defense')
        check(await pg.locator('.pf table:has-text("ก่อนเรียน") tbody tr').count()==18,'18 weeks listed')
        ta=wl.locator('textarea'); await ta.fill('วาง AP ใหม่ให้พ้นผนังคอนกรีต ครอบคลุมทั้งสองห้อง'); await wl.locator('button:has-text("บันทึก")').click()
        await pg.wait_for_selector('#pf-wireless .pfmsg.ok'); await pg.reload(); await pg.wait_for_selector('#pf-wireless textarea')
        check('พ้นผนังคอนกรีต' in await pg.locator('#pf-wireless textarea').input_value(),'reflection saved and shown after reload')
        await pg.screenshot(path=f'{OUT}/p14_portfolio_1366.png',full_page=True)
        await pg.emulate_media(media='print')
        hidden=await pg.evaluate("[...document.querySelectorAll('.pf .noprint')].every(e=>getComputedStyle(e).display==='none')")
        side=await pg.evaluate("getComputedStyle(document.querySelector('.side')).visibility")
        check(hidden and side=='hidden','print view hides buttons, forms and the app menu')
        pdf=await pg.pdf(format='A4'); check(len(pdf)>20000,f'portfolio prints to PDF ({len(pdf)//1024} KB)')
        open(f'{OUT}/p14_portfolio.pdf','wb').write(pdf)
        await pg.emulate_media(media='screen')
        check(not E,'no page errors '+'; '.join(E[:2]))
        P=await b.new_context(viewport={'width':390,'height':844},has_touch=True,is_mobile=True); await login(P,'s1','Stud1234'); pp=await P.new_page()
        await pp.goto(BASE+'/#/portfolio'); await pp.wait_for_selector('.pf .pfsk'); await pp.wait_for_timeout(300)
        ov=await pp.evaluate('document.documentElement.scrollWidth-innerWidth'); check(ov<=0,f'no horizontal page scroll at 390px ({ov})')
        await pp.screenshot(path=f'{OUT}/p14_portfolio_390.png'); await P.close()

        print('== teacher: class overview, evidence, comments, defense rubric')
        T=await b.new_context(viewport={'width':1366,'height':900}); await login(T,'kru4','Teach1234'); tp=await T.new_page(); TE=[]; tp.on('pageerror',lambda e:TE.append(str(e)))
        tp.on('dialog',lambda d: asyncio.ensure_future(d.accept()))
        await tp.goto(BASE+'/teacher.html'); await tp.wait_for_selector('.side')
        await tp.locator('.side .navbtn').nth(1).click(); await tp.wait_for_selector('.tabs')
        await tp.locator('.tabs button',has_text='แฟ้มผลงานทักษะ').click(); await tp.wait_for_selector('button:has-text("เปิดแฟ้ม")')
        row=await tp.locator('tr:has-text("สมชาย ทดสอบ")').inner_text()
        check('26/30' in row,'class overview shows the capstone score (* = report not yet reviewed)')
        await tp.screenshot(path=f'{OUT}/p14_teacher_class.png',full_page=True)
        await tp.locator('tr:has-text("สมชาย ทดสอบ") button:has-text("เปิดแฟ้ม")').click(); await tp.wait_for_selector('.pf #pf-cabling')
        cab=tp.locator('#pf-cabling'); await cab.locator('summary').click()
        await cab.locator('select[aria-label="ระดับที่สังเกต"]').select_option('3'); await cab.locator('input[aria-label="สิ่งที่นักเรียนทำ"]').fill('เข้าหัว RJ-45 จริง 2 เส้น ผ่าน LAN tester')
        await cab.locator('input[aria-label="สัปดาห์"]').fill('5'); await cab.locator('button:has-text("บันทึกหลักฐาน")').click()
        await tp.wait_for_function("document.querySelector('#pf-cabling') && document.querySelector('#pf-cabling').innerText.includes('ครูบันทึกจากการปฏิบัติจริง')")
        check('ระดับ 3/4' in await tp.inner_text('#pf-cabling'),'teacher records class evidence; it appears in the evidence table')
        wl=tp.locator('#pf-wireless'); check('พ้นผนังคอนกรีต' in await wl.inner_text(),'teacher reads the student reflection')
        await wl.locator('textarea[aria-label^="ความเห็นครู"]').fill('ดีมาก ลองลดกำลังส่งดูด้วย'); await wl.locator('button:has-text("บันทึกความเห็น")').click(); await tp.wait_for_selector('#pf-wireless .pfmsg.ok')
        cap=tp.locator('#pf-capstone')
        for cid,v in [('อธิบายการออกแบบและแผน IP','3'),('สาธิตการทำงานและการทดสอบ','4'),('แก้ปัญหาเฉพาะหน้าที่ครูกำหนด','3')]:
            await cap.locator(f'select[aria-label="ระดับ {cid}"]').select_option(v)
        await cap.locator('textarea').first.fill('สาธิตครบ อธิบาย VLSM ได้ชัด'); await cap.locator('button:has-text("บันทึกการประเมินการนำเสนอ")').click()
        await tp.wait_for_function("document.querySelector('#pf-capstone') && document.querySelector('#pf-capstone').innerText.includes('10/20')")
        ok('teacher scores the defense rubric (3+4+3 = 10/20, two criteria left unscored)')
        await tp.screenshot(path=f'{OUT}/p14_teacher_portfolio.png',full_page=True)
        check(not TE,'no page errors on the teacher page '+'; '.join(TE[:2]))

        print('== student sees the teacher\'s work')
        await pg.reload(); await pg.wait_for_selector('#pf-cabling')
        check('ครูบันทึกจากการปฏิบัติจริง' in await pg.inner_text('#pf-cabling') and 'ลองลดกำลังส่ง' in await pg.inner_text('#pf-wireless'),'observation and comment appear in the student portfolio')
        check('10/20' in await pg.inner_text('#pf-capstone'),'defense score appears in the student portfolio')
        check(await pg.locator('#pf-capstone textarea[aria-label^="ความเห็นครู"]').count()==0,'student cannot edit the teacher comment')

        print('== class option: Guided Lab before the post-test')
        await tp.locator('.tabs button',has_text='ตั้งค่าห้อง').click(); await tp.wait_for_selector('text=บังคับฝึกปฏิบัติก่อนสอบหลังเรียน')
        await tp.locator('.card:has-text("บังคับฝึกปฏิบัติ") input[type=checkbox]').check(); await tp.wait_for_timeout(800)
        check(sql("SELECT require_practice FROM classes LIMIT 1")=='t','teacher turns the option on')
        await pg.goto(BASE+'/#/lesson/w1/post'); await pg.wait_for_selector('.gatebox')
        g=await pg.inner_text('.gatebox'); dis=await pg.locator('.quizbar button').is_disabled()
        check('ฝึกปฏิบัติรวมของสัปดาห์' in g and await pg.locator('.gatebox a[href="#/lesson/w1/lab"]').count()==1 and dis,'post-test points to the week practical (3.2: one practical session) and cannot be sent')
        await pg.screenshot(path=f'{OUT}/p14_gate.png')
        # pass the week 1 practical: one session, results as the server records them during it (real answers are tested in part20)
        r=await S.request.post(BASE+'/api/practical/w1/start',headers={'X-NetLab':'1'}); j=await r.json(); assert r.ok, j
        keys=[(i['key'],p_['id']) for p_ in j['parts'] for i in p_['items']]
        sql("INSERT INTO practical_items(session_id,item,part,score,max,solved) VALUES "+','.join(f"({j['running']['id']},'{k}','{pt}',10,10,true)" for k,pt in keys))
        r=await S.request.post(BASE+'/api/practical/w1/submit',headers={'X-NetLab':'1'}); j=await r.json(); check(r.ok and j['best']['passed'],'week 1 practical passed')
        await pg.reload(); await pg.wait_for_selector('.quiz'); await pg.wait_for_timeout(1200)
        check(await pg.locator('.gatebox').count()==0,'after passing the week practical the lock disappears')
        await tp.locator('.card:has-text("บังคับฝึกปฏิบัติ") input[type=checkbox]').uncheck(); await tp.wait_for_timeout(800)
        check(sql("SELECT require_practice FROM classes LIMIT 1")=='f','teacher turns the option off again')
        await b.close()
    print(f'\npart14: {len(issues)} issue(s)'); sys.exit(1 if issues else 0)
asyncio.run(main())
